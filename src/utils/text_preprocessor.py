def is_korean_jamo(char: str) -> bool:
    """
    문자가 한국어 자모(ㄱ-ㅎ, ㅏ-ㅣ)인지 확인합니다.
    
    Args:
        char: 확인할 문자
        
    Returns:
        한국어 자모이면 True, 아니면 False
    """
    if len(char) != 1:
        return False
    code = ord(char)
    # ㄱ-ㅎ: U+3131 ~ U+314E (12593 ~ 12622)
    # ㅏ-ㅣ: U+314F ~ U+3163 (12623 ~ 12643)
    return 0x3131 <= code <= 0x3163


def preprocess_text(text: str) -> str:
    """
    TTS 변환 전 텍스트를 전처리합니다.
    
    한국어 초성 약어를 완성형 단어로 변환합니다.
    단, 더 긴 초성 문자열의 일부인 경우는 변환하지 않습니다.
    
    예시:
        - "ㄱㅅ" -> "감사" (독립된 초성 약어이므로 변환)
        - "ㅂㅈㅅㅈ" -> "ㅂㅈㅅㅈ" (더 긴 초성 문자열이므로 변환 안 함)
        - "안녕 ㄱㅅ" -> "안녕 감사" (독립된 초성 약어이므로 변환)
    
    Args:
        text: 원본 텍스트
        
    Returns:
        전처리된 텍스트
    """
    if not text:
        return text
    
    # URL을 "링크"로 변환
    text = re.sub(r'https?://\S+', '링크', text)
    
    # 초성 블록들을 찾아 처리
    result = []
    i = 0
    
    while i < len(text):
        # 현재 위치에서 시작하는 초성 블록 찾기
        if is_korean_jamo(text[i]):
            # 연속된 자모 문자열 수집
            jamo_start = i
            jamo_end = i
            
            while jamo_end < len(text) and is_korean_jamo(text[jamo_end]):
                jamo_end += 1
            
            jamo_block = text[jamo_start:jamo_end]
            
            # 정확히 일치하는 약어가 있으면 변환
            if jamo_block in KOREAN_ABBREVIATIONS:
                result.append(KOREAN_ABBREVIATIONS[jamo_block])
            else:
                # 일치하는 약어가 없으면 원본 유지
                result.append(jamo_block)
            
            i = jamo_end
        else:
            result.append(text[i])
            i += 1
    
    return ''.join(result)
